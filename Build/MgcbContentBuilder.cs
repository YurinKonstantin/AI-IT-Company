using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

namespace Build;

/// <summary>
/// После генерации спрайтов Artist: обновляет Content.mgcb и документирует
/// рекомендуемый путь загрузки через Texture2D.FromStream.
/// </summary>
public static class MgcbContentBuilder
{
    public sealed record Result(int SpriteCount, string? MgcbPath, string? ReadmePath, string Summary);

    public static async Task<Result> EnsureAsync(string projectRoot, CancellationToken ct = default)
    {
        if (string.IsNullOrWhiteSpace(projectRoot) || !Directory.Exists(projectRoot))
            return new Result(0, null, null, "project root missing");

        var contentDir = Path.Combine(projectRoot, "Content");
        var spritesDir = Path.Combine(contentDir, "Sprites");
        if (!Directory.Exists(spritesDir))
            return new Result(0, null, null, "no Content/Sprites");

        var pngs = Directory.EnumerateFiles(spritesDir, "*.png", SearchOption.AllDirectories)
            .OrderBy(p => p, StringComparer.OrdinalIgnoreCase)
            .ToList();

        if (pngs.Count == 0)
            return new Result(0, null, null, "no PNG sprites");

        PathHelperEnsure(contentDir);

        var mgcbPath = Path.Combine(contentDir, "Content.mgcb");
        var mgcb = BuildMgcb(contentDir, pngs);
        await File.WriteAllTextAsync(mgcbPath, mgcb, ct);

        var readmePath = Path.Combine(contentDir, "LOADING.md");
        await File.WriteAllTextAsync(readmePath, BuildLoadingDoc(pngs.Count), ct);

        // Убедимся, что CopyToOutputDirectory есть (Artist тоже ставит; идемпотентно).
        EnsureContentCopyToOutput(projectRoot);

        var summary = $"MGCB: {pngs.Count} texture(s) → Content/Content.mgcb; see Content/LOADING.md (FromStream)";
        return new Result(pngs.Count, mgcbPath, readmePath, summary);
    }

    private static string BuildMgcb(string contentDir, List<string> pngFullPaths)
    {
        var sb = new StringBuilder();
        sb.AppendLine("#----------------------------- Global Properties ----------------------------#");
        sb.AppendLine();
        sb.AppendLine("/outputDir:bin/DesktopGL/Content");
        sb.AppendLine("/intermediateDir:obj/DesktopGL/Content");
        sb.AppendLine("/platform:DesktopGL");
        sb.AppendLine("/config:");
        sb.AppendLine("/profile:Reach");
        sb.AppendLine("/compress:False");
        sb.AppendLine();
        sb.AppendLine("#-------------------------------- References --------------------------------#");
        sb.AppendLine();
        sb.AppendLine();
        sb.AppendLine("#---------------------------------- Content ---------------------------------#");
        sb.AppendLine();
        sb.AppendLine("# Auto-generated by AI IT-Company after Artist. Primary runtime path is PNG + FromStream;");
        sb.AppendLine("# build with `dotnet tool run mgcb` / MonoGame Content Builder if you need .xnb.");
        sb.AppendLine();

        foreach (var full in pngFullPaths)
        {
            var rel = Path.GetRelativePath(contentDir, full).Replace('\\', '/');
            sb.AppendLine($"#begin {rel}");
            sb.AppendLine("/importer:TextureImporter");
            sb.AppendLine("/processor:TextureProcessor");
            sb.AppendLine("/processorParam:ColorKeyColor=255,0,255,255");
            sb.AppendLine("/processorParam:ColorKeyEnabled=False");
            sb.AppendLine("/processorParam:GenerateMipmaps=False");
            sb.AppendLine("/processorParam:PremultiplyAlpha=True");
            sb.AppendLine("/processorParam:ResizeToPowerOfTwo=False");
            sb.AppendLine("/processorParam:MakeSquare=False");
            sb.AppendLine("/processorParam:TextureFormat=Color");
            sb.AppendLine($"/build:{rel}");
            sb.AppendLine();
            sb.AppendLine($"#endregion {rel}");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    private static string BuildLoadingDoc(int count) => $"""
        # Content loading (MonoGame)

        AI IT-Company generated **{count}** PNG sprite(s) under `Content/Sprites/`.

        ## Recommended (default)

        Load PNGs at runtime — no MGCB build step required:

        ```csharp
        using var stream = TitleContainer.OpenStream("Content/Sprites/player.png");
        var tex = Texture2D.FromStream(GraphicsDevice, stream);
        ```

        The `.csproj` should copy `Content/**` to the output directory (`CopyToOutputDirectory`).
        See also `Content/assets.manifest.json` for the asset list.

        ## Optional: MGCB → .xnb

        `Content/Content.mgcb` lists the same textures for MonoGame Content Pipeline.
        Use only if you prefer compiled `.xnb` assets:

        ```text
        dotnet tool install -g dotnet-mgcb
        mgcb /@:Content/Content.mgcb
        ```

        Then load via `Content.Load<Texture2D>("Sprites/player")` (without extension).
        """;

    private static void EnsureContentCopyToOutput(string root)
    {
        var projects = NuGetPackageResolver.FindProjectFiles(root);
        foreach (var csproj in projects)
        {
            string text;
            try { text = File.ReadAllText(csproj); }
            catch { continue; }

            if (text.Contains("Content\\**", StringComparison.OrdinalIgnoreCase)
                || text.Contains("Content/**", StringComparison.OrdinalIgnoreCase))
                continue;

            bool looksGame = text.Contains("MonoGame", StringComparison.OrdinalIgnoreCase)
                || Path.GetFileNameWithoutExtension(csproj)
                    .Contains("Game", StringComparison.OrdinalIgnoreCase)
                || projects.Count == 1;
            if (!looksGame) continue;

            const string snippet = """

  <ItemGroup>
    <None Update="Content\**\*">
      <CopyToOutputDirectory>PreserveNewest</CopyToOutputDirectory>
    </None>
  </ItemGroup>
""";
            var idx = text.LastIndexOf("</Project>", StringComparison.OrdinalIgnoreCase);
            if (idx < 0) continue;
            text = text.Insert(idx, snippet + Environment.NewLine);
            File.WriteAllText(csproj, text);
            break;
        }
    }

    private static void PathHelperEnsure(string dir)
    {
        if (!Directory.Exists(dir))
            Directory.CreateDirectory(dir);
    }
}
